# Import library dasar dan machine learning
import pandas as pd
import numpy as np
import matplotlib.pyplot as plt
import seaborn as sns

from sklearn.model_selection import train_test_split
from sklearn.preprocessing import StandardScaler, LabelEncoder
from sklearn.ensemble import RandomForestClassifier
from sklearn.metrics import accuracy_score, classification_report, confusion_matrix

# Memuat dataset
df = pd.read_csv('loan_approval_dataset.csv')

# Membersihkan nama kolom dari spasi berlebih
df.columns = df.columns.str.strip()

# Menghapus kolom 'loan_id' karena hanya nomor unik dan tidak berpengaruh untuk prediksi
if 'loan_id' in df.columns:
    df = df.drop(columns=['loan_id'])

# Membersihkan spasi pada nilai teks (string)
for col in df.select_dtypes(include=['object']).columns:
    df[col] = df[col].str.strip()

# Mengubah data kategorikal (teks) menjadi angka menggunakan LabelEncoder
le_education = LabelEncoder()
df['education'] = le_education.fit_transform(df['education'])

le_self = LabelEncoder()
df['self_employed'] = le_self.fit_transform(df['self_employed'])

le_status = LabelEncoder()
df['loan_status'] = le_status.fit_transform(df['loan_status']) # Approved / Rejected

print("5 Data Teratas Setelah Preprocessing:")
display(df.head())

print("\nCek Missing Values:")
print(df.isnull().sum())

# Menentukan fitur (X) dan target (y)
X = df.drop(columns=['loan_status'])
y = df['loan_status']

# Standarisasi fitur agar memiliki skala yang seragam
scaler = StandardScaler()
X_scaled = scaler.fit_transform(X)

# Membagi data menjadi 80% data latih dan 20% data uji
X_train, X_test, y_train, y_test = train_test_split(
    X_scaled, y, test_size=0.2, random_state=42
)

print(f"Jumlah Data Latih: {X_train.shape[0]}")
print(f"Jumlah Data Uji: {X_test.shape[0]}")

# Menggunakan algoritma Random Forest Classifier
model = RandomForestClassifier(random_state=42)

# Melatih model dengan data latih
model.fit(X_train, y_train)

print("Model Random Forest berhasil dilatih!")

# Menggunakan algoritma Random Forest Classifier
model = RandomForestClassifier(random_state=42)

# Melatih model menggunakan data latih
model.fit(X_train, y_train)

print("Model berhasil dilatih!")

# Melakukan prediksi pada data uji
y_pred = model.predict(X_test)

# Menghitung akurasi
accuracy = accuracy_score(y_test, y_pred)
print(f"Akurasi Model: {accuracy * 100:.2f}%\n")

# Menampilkan Classification Report
print("Classification Report:")
print(classification_report(y_test, y_pred, target_names=le_status.classes_))

# Visualisasi Confusion Matrix
plt.figure(figsize=(6, 4))
sns.heatmap(confusion_matrix(y_test, y_pred), annot=True, cmap='Greens', fmt='d',
            xticklabels=le_status.classes_, yticklabels=le_status.classes_)
plt.title('Confusion Matrix - Loan Approval')
plt.xlabel('Prediksi')
plt.ylabel('Aktual')
plt.show()

# --- KESIMPULAN ---
print("=== KESIMPULAN ===")
print(f"1. Model klasifikasi pinjaman menggunakan Random Forest mencapai akurasi sebesar {accuracy * 100:.2f}%.")
print("2. Faktor seperti skor CIBIL, pendapatan tahunan, dan jumlah pinjaman terbukti sangat menentukan status persetujuan pinjaman.")

